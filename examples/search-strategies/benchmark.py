"""Deterministic external benchmark used to dogfood benchpub."""

from __future__ import annotations

import argparse
import json
from collections.abc import Callable
from pathlib import Path

SearchFunction = Callable[[list[int], int], tuple[bool, int]]


def linear_search(data: list[int], target: int) -> tuple[bool, int]:
    comparisons = 0
    for value in data:
        comparisons += 1
        if value == target:
            return True, comparisons
    return False, comparisons


def binary_search(data: list[int], target: int) -> tuple[bool, int]:
    low = 0
    high = len(data) - 1
    comparisons = 0

    while low <= high:
        middle = (low + high) // 2
        value = data[middle]
        comparisons += 1

        if value == target:
            return True, comparisons
        if value < target:
            low = middle + 1
        else:
            high = middle - 1

    return False, comparisons


def evaluate(
    search: SearchFunction,
    data: list[int],
    queries: list[int],
) -> tuple[int, int]:
    total_comparisons = 0
    found_queries = 0

    for target in queries:
        found, comparisons = search(data, target)
        total_comparisons += comparisons
        found_queries += int(found)

    return total_comparisons, found_queries


def result_manifest(
    *,
    variant: str,
    algorithm: str,
    total_comparisons: int,
    found_queries: int,
    query_count: int,
) -> dict[str, object]:
    return {
        "schema_version": 1,
        "experiment": {
            "id": "search-strategies-001",
            "name": "Linear vs binary search",
            "hypothesis": (
                "Binary search reduces comparisons for sorted lookup workloads."
            ),
            "variant": variant,
        },
        "dataset": {
            "name": "deterministic-integer-lookups",
            "revision": "v1",
        },
        "metrics": [
            {
                "name": "comparisons_total",
                "value": total_comparisons,
                "unit": "comparisons",
                "direction": "lower",
            },
            {
                "name": "comparisons_mean",
                "value": total_comparisons / query_count,
                "unit": "comparisons/query",
                "direction": "lower",
            },
            {
                "name": "found_queries",
                "value": found_queries,
                "unit": "queries",
                "direction": "none",
            },
        ],
        "controlled_variables": {
            "dataset_size": 1000,
            "query_count": query_count,
            "query_formula": "(i * 97) % 1500",
            "sorted": True,
        },
        "configuration": {
            "algorithm": algorithm,
        },
        "notes": (
            "Generated by examples/search-strategies/benchmark.py. "
            "benchpub did not execute this benchmark."
        ),
    }


def write_manifest(path: Path, manifest: dict[str, object]) -> None:
    path.write_text(
        json.dumps(manifest, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate deterministic linear-vs-binary search benchmark results."
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).with_name("results"),
        help="Directory where baseline.json and treatment.json are written.",
    )
    args = parser.parse_args()

    data = list(range(1000))
    queries = [(index * 97) % 1500 for index in range(200)]

    linear_comparisons, linear_found = evaluate(linear_search, data, queries)
    binary_comparisons, binary_found = evaluate(binary_search, data, queries)

    args.output.mkdir(parents=True, exist_ok=True)
    write_manifest(
        args.output / "baseline.json",
        result_manifest(
            variant="linear",
            algorithm="linear_search",
            total_comparisons=linear_comparisons,
            found_queries=linear_found,
            query_count=len(queries),
        ),
    )
    write_manifest(
        args.output / "treatment.json",
        result_manifest(
            variant="binary",
            algorithm="binary_search",
            total_comparisons=binary_comparisons,
            found_queries=binary_found,
            query_count=len(queries),
        ),
    )


if __name__ == "__main__":
    main()
